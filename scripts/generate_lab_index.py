#!/usr/bin/env python3
"""Regenerate LAB-INDEX.md from the Category/lab/README.md hierarchy.
Reads the 'Overview' bullet fields from each lab README. Standard library only.
Usage: python3 scripts/generate_lab_index.py
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SKIP = {"templates", "scripts", ".github"}
FIELDS = {
    "difficulty": r"Official difficulty:\s*(.+)",
    "doc": r"Documentation status:\s*(.+)",
    "done": r"Completion status:\s*(.+)",
    "evidence": r"Evidence status:\s*(.+)",
}

def field(text, pattern):
    m = re.search(pattern, text)
    return re.sub(r"\s*\(.*\)$", "", m.group(1).strip()) if m else "Unknown"

rows, counts = [], {}
for cat in sorted(p for p in ROOT.iterdir() if p.is_dir() and not p.name.startswith(".") and p.name not in SKIP):
    for lab in sorted(p for p in cat.iterdir() if p.is_dir()):
        readme = lab / "README.md"
        if not readme.exists():
            continue
        text = readme.read_text(encoding="utf-8")
        title = text.splitlines()[0].lstrip("# ").strip()
        v = {k: field(text, p) for k, p in FIELDS.items()}
        counts[v["done"]] = counts.get(v["done"], 0) + 1
        rel = f"{cat.name}/{lab.name}/README.md"
        rows.append(f"| {title} | {cat.name.replace('-', ' ')} | {v['difficulty']} | {v['doc']} | {v['done']} | {v['evidence']} | [Open report]({rel}) |")

out = ["# Lab Index", "", "Generated by `scripts/generate_lab_index.py` from the lab reports. Do not edit by hand.", "",
       "| Lab Title | Category | Difficulty | Documentation Status | Completion Status | Evidence Status | Report |",
       "|---|---|---|---|---|---|---|", *rows, "", f"**Total lab directories:** {len(rows)}", ""]
out += [f"- {k}: {n}" for k, n in sorted(counts.items())]
(ROOT / "LAB-INDEX.md").write_text("\n".join(out) + "\n", encoding="utf-8")
print(f"Indexed {len(rows)} lab(s).")
